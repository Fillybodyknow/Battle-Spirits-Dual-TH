/**
 * ข้อมูลโหมด Story (SOLO → STORIES): แต่ละ "ด่าน" (Gate) = แผนที่ของโหนด เนื้อเรื่อง / ฝึกซ้อม / ดวล / เป้าหมาย
 *
 * เขียนด่านใหม่: เพิ่ม object ใน GATES
 *  - cardNo = การ์ดหน้าปกของด่าน (ภาพในรายการ + ฉากเปิดการ์ด)
 *  - nodes: ตำแหน่งบนแผนที่ = col (ซ้าย→ขวา) / row (0 = แถวบน, 1 = กลาง, 2 = ล่าง: ใช้แถว 2 = แผนที่ 3 แถว) · after = โหนดที่ต้องผ่านก่อนทุกโหนด (ปลดล็อก + เส้นเชื่อม)
 *    afterAny = ทางแยกให้เลือก (ผ่านโหนดใดโหนดหนึ่งก็พอ) · โหนดที่ไม่มีใครต่อจาก = ทางเสริม (เล่นหรือไม่ก็ได้ ไม่กระทบตรา)
 *  - scenario / goal: lines = บทพูดทีละกล่อง (speaker ว่าง = คำบรรยาย)
 *  - practice: ใช้เด็คที่ด่านให้ยืม (playerDeck) · duel: ผู้เล่นเลือกเด็คเอง (หรือใช้เด็คยืมของด่านก็ได้)
 *  - stars 1–6 = ความเก่งของบอท (6 = คิดล่วงหน้าอีกหนึ่งท่า) · botDeck = เด็คของคู่แข่ง (รหัส Starter เช่น 'sd02' หรือ deck(...) ด้านล่าง)
 *  - locked: true = โหนดกั้น (ผ่านอัตโนมัติเมื่อโหนดใน after ผ่านครบ ใช้แยกเส้นทางด่านพิเศษ)
 * ความคืบหน้าเก็บใน localStorage 'bs-solo' (ซิงก์ตามบัญชี)
 */
import type { DeckEntry } from '@bs/cards';
import { encodeDeck, type DeckId } from '../decks';

export interface StoryLine {
  /** ชื่อผู้พูด (ว่าง = คำบรรยาย) */
  speaker?: string;
  text: string;
}

export type GateNodeKind = 'scenario' | 'practice' | 'duel' | 'goal' | 'locked';

export interface GateNode {
  id: string;
  kind: GateNodeKind;
  col: number;
  /** แถว 0–2 (บทที่ใช้แถว 2 = แผนที่ 3 แถว) */
  row: 0 | 1 | 2;
  after?: string[];
  /** ทางแยกให้เลือก: ผ่านโหนดใดโหนดหนึ่งในนี้ก็ปลดล็อก (ใช้คู่กับ after ได้) */
  afterAny?: string[];
  title?: string;
  lines?: StoryLine[];
  stars?: number;
  /** ชื่อคู่แข่งบนกระดาน */
  opponent?: string;
  /** รูปโปรไฟล์ของคู่แข่ง (รหัสการ์ด · ไม่ระบุ = การ์ดหน้าปกของด่าน) · โหนดดวล/ฝึกซ้อมใช้เป็นภาพพื้นหลังของโหนดด้วย */
  avatar?: string;
  /** ภาพพื้นหลังของโหนดเนื้อเรื่อง/เป้าหมาย/กั้น (รหัสการ์ดที่ภาพเข้ากับฉาก · ไม่ระบุ = การ์ดหน้าปกของด่าน) */
  art?: string;
  /** คำอธิบายในแผงด่านดวล (ไม่ระบุ = ชื่อคู่แข่ง + เด็ค) */
  description?: string;
  /** คำอธิบายเด็คของคู่แข่ง (หน้าดูเด็คคู่แข่ง) */
  deckDescription?: string;
  /** practice: บทเรียนสอนเด็คของแคว้น (id ใน solo/lessons.ts) แทนการดวลกับบอท */
  lesson?: string;
  botDeck?: DeckId;
  /** เด็คที่ด่านให้ยืม (practice บังคับใช้ · duel เลือกได้) */
  playerDeck?: DeckId;
}

export interface Gate {
  id: string;
  title: string;
  /** การ์ดหน้าปก */
  cardNo: string;
  /** คำอธิบายด่าน (แผงรายละเอียด) */
  description: string;
  nodes: GateNode[];
  /** กลุ่มในหน้า Stories: sengoku = ยุคสมัยแห่งเซ็นโงคุ · special = ด่านพิเศษ */
  era?: 'sengoku' | 'special';
  /** ตราแคว้น (ได้เมื่อผ่านเป้าหมายของบท) */
  emblem?: { name: string; color: string };
  /** ต้องผ่านบทเหล่านี้ (ถึงเป้าหมาย) ก่อนถึงจะเล่นได้ */
  requires?: string[];
  /** ยังไม่เปิด (แสดงเป็น "เร็ว ๆ นี้") */
  soon?: boolean;
}

